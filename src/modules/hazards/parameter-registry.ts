/**
 * Get all parameters matching a category
 */
export function getParametersByCategory(category: ParameterCategory): EnvironmentalParameterDefinition[] {
  return Object.values(ENVIRONMENTAL_PARAMETER_REGISTRY).filter((p) => {
    if (category === "derived_indicators") {
      return p.category === "derived_indicators" || p.isDerived === true || p.dataType === "DERIVED" || p.endpoint === "derived";
    }
    if (category === "historical_archive") {
      return p.category === "historical_archive" || p.dataType === "HISTORICAL_REANALYSIS" || p.endpoint === "archive";
    }
    return p.category === category;
  });
}

/**
 * Filter registry parameters by category and city applicability
 */
export function getParametersForCityAndCategory(
  city: "mumbai" | "pune" | "nagpur",
  category?: ParameterCategory
): EnvironmentalParameterDefinition[] {
  return Object.values(ENVIRONMENTAL_PARAMETER_REGISTRY).filter((p) => {
    if (!p.supportedCities.includes(city)) return false;
    if (!category) return true;
    if (category === "derived_indicators") {
      return p.category === "derived_indicators" || p.isDerived === true || p.dataType === "DERIVED" || p.endpoint === "derived";
    }
    if (category === "historical_archive") {
      return p.category === "historical_archive" || p.dataType === "HISTORICAL_REANALYSIS" || p.endpoint === "archive";
    }
    return p.category === category;
  });
}

/**
 * Get definition by ID with fallback
 */
export function getParameterDefinition(id: string): EnvironmentalParameterDefinition | undefined {
  return ENVIRONMENTAL_PARAMETER_REGISTRY[id];
}

