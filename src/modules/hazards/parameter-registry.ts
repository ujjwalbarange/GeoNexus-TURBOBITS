export type ParameterCategory =
  | "weather_atmosphere"
  | "rainfall_hydrology"
  | "air_quality"
  | "heat_exposure"
  | "coastal_marine"
  | "soil_land"
  | "historical_archive"
  | "derived_indicators";

export type ParameterDataType =
  | "MEASURED"
  | "MODELLED_CURRENT"
  | "FORECAST"
  | "HISTORICAL_REANALYSIS"
  | "ARCHIVED_SNAPSHOT"
  | "DERIVED";

export type ParameterTemporality =
  | "INSTANTANEOUS"
  | "HOURLY"
  | "DAILY"
  | "ROLLING_ACCUMULATION"
  | "DERIVED";

export interface ParameterThreshold {
  level: "ADVISORY" | "WATCH" | "WARNING" | "CRITICAL";
  min?: number;
  max?: number;
  label: string;
  color: string;
  sourceAuthority: string; // e.g. "IMD", "WHO", "US EPA", "CPCB", "NOAA"
}

export interface EnvironmentalParameterDefinition {
  id: string;
  label: string;
  category: ParameterCategory;
  description: string;
  unit: string;
  endpoint: "weather" | "air_quality" | "marine" | "flood" | "archive" | "derived";
  apiField: string;
  model: string;
  dataType: ParameterDataType;
  temporality: ParameterTemporality;
  supportedCities: Array<"mumbai" | "pune" | "nagpur">;
  spatialResolution: string;
  temporalResolution: string;
  thresholds?: ParameterThreshold[];
  formula?: string;
  license: string;
  attribution: string;
  isDerived?: boolean;
  derivedInputs?: string[];
  whatItMeasures?: string;
  plainLanguageMeaning?: string;
  whyItMatters?: string;
  limitations?: string;
  associatedAnalysis?: string;
}

