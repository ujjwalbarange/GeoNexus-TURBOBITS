/** Check if a department exists in the given city */
export function isDepartmentConfiguredForCity(city: CitySlug, departmentCode: string): boolean {
  const cityProfiles = CITY_DEPARTMENT_PROFILES[city];
  return !!cityProfiles && !!cityProfiles[departmentCode];
}

/** Get all available department codes for a city */
export function getCityConfiguredDepartments(city: CitySlug): string[] {
  const cityProfiles = CITY_DEPARTMENT_PROFILES[city];
  return cityProfiles ? Object.keys(cityProfiles) : [];
}

/** Get department profile for a city */
export function getCityDepartmentProfile(city: CitySlug, departmentCode: string): CityDepartmentProfile | null {
  return CITY_DEPARTMENT_PROFILES[city]?.[departmentCode] || null;
}
